import pandas as pd
import plotly.graph_objects as go
import streamlit as st

from .artifacts import ArtifactError
from .charts import style
from .sql_demo import APPROVED_SQL, explain_result, load_sql_bundle, run_approved_query
from .ui import DOCS, REPOSITORY


def result_chart(identity, result):
    if identity == "weekday":
        days = ("Sunday", "Monday", "Tuesday", "Wednesday", "Thursday", "Friday", "Saturday")
        figure = go.Figure(go.Bar(x=[days[int(r[0])] for r in result["rows"]],
                                  y=[r[1] for r in result["rows"]], marker_color="#167E87"))
        figure.update_xaxes(title="NYC-local weekday of sampled ride start")
        figure.update_yaxes(title="Accepted sampled starts", rangemode="tozero")
        return style(figure, "Starts by weekday - sample only")
    if identity == "top_station" and result["rows"]:
        figure = go.Figure(go.Bar(x=[str(r[0]) for r in result["rows"]],
                                  y=[r[1] for r in result["rows"]], marker_color="#167E87"))
        figure.update_xaxes(title="Exact station ID", type="category")
        figure.update_yaxes(title="Accepted sampled starts", rangemode="tozero")
        return style(figure, "Highest sample count - not a citywide ranking")
    return None


def sqlpilot_workspace():
    st.caption("ANALYTICS / CURATED OFFLINE SQL")
    st.title("SQLPilot")
    st.write("Ask better questions of mobility data, with explicit tools and guardrails. This workspace executes fixed reference SQL on a real, small Citi Bike sample.")
    st.info("Curated offline SQL demonstration. No live LLM generation, Groq request, MCP session or cloud connection is made here.")
    try:
        data = load_sql_bundle()
    except ArtifactError:
        st.error("The verified analytical sample or query bundle is missing or invalid. No answers have been invented.")
        return
    manifest = data["manifest"]
    metrics = st.columns(3)
    metrics[0].metric("Accepted sampled trips", f"{manifest['sample_rows']['validated_trips']:,}")
    metrics[1].metric("Sample station-hour records", f"{manifest['sample_rows']['hourly_rides']:,}")
    metrics[2].metric("Approved reference queries", str(len(APPROVED_SQL)))
    st.caption("First 1,000 rows from each of two January 2024 archive members, not the final 100-station dataset. Archive-month and NYC-local start dates differ at boundaries. Sparse sample rows do not certify zero physical demand or operating availability.")
    st.subheader("Explore an approved analytical question")
    identity = st.selectbox("Approved analytical question", list(APPROVED_SQL),
                            format_func=lambda value: data["queries"][value]["question"], key="sql_question")
    record = data["queries"][identity]
    st.caption("Curated reference SQL - selected by question ID, not generated by a model.")
    st.code(record["sql"], language="sql")
    if st.button("Run approved SQL", key="sql_run", type="primary"):
        st.session_state.pop("sql_demo_result", None)
        try:
            with st.spinner("Executing the approved read-only query..."):
                result = run_approved_query(identity, data["directory"])
            st.session_state["sql_demo_result"] = {"query_id": identity, "result": result}
        except (ArtifactError, ImportError):
            st.error("The approved query could not complete safely. No automatic retry or invented result was used.")
    saved = st.session_state.get("sql_demo_result")
    if saved and saved["query_id"] == identity:
        result = saved["result"]
        st.subheader("Verified query result")
        if not result["rows"]:
            st.info("No rows matched this sample query. An empty result is not evidence of zero physical demand.")
        else:
            st.dataframe(pd.DataFrame(result["rows"], columns=result["columns"]), hide_index=True, width="stretch")
            if all(value is None for row in result["rows"] for value in row):
                st.info("SQL returned NULL: SUM has no matching input records. NULL is preserved, not converted into a zero count.")
            else:
                st.write(explain_result(identity, result))
            chart = result_chart(identity, result)
            if chart is not None:
                st.plotly_chart(chart, theme=None, width="stretch", key="sql_result_chart")
        st.success("Executed locally and matched the verified original-sample reference result.")
        st.caption(f"Measured local execution: {result['latency_seconds']:.3f}s including worker startup. "
                   "This is not the historical LLM benchmark latency. The original source database is not accessed at runtime.")
    st.subheader("Original agent architecture")
    st.markdown("""<div style="display:flex;flex-wrap:wrap;gap:.6rem;align-items:center;padding:1rem;border:1px solid #CBD9E2;border-radius:12px;background:#FFFFFF;color:#21384B">
    <strong>Question</strong> → <strong>LangGraph</strong> → <strong>Groq LLM / candidate SQL</strong> →
    <strong>MCP tools</strong> → <strong>SQL guardrails</strong> → <strong>DuckDB</strong> → <strong>Results</strong>
    </div>""", unsafe_allow_html=True)
    st.caption("Above: the existing original agent. This public demo instead uses approved question ID → fixed SQL → the same validator → isolated read-only DuckDB → checked result. It does not simulate a live agent trace.")
    with st.expander("What the original components do"):
        st.markdown("**LangGraph** carries question/schema/attempt state between schema discovery, generation, execution, bounded repair and explanation. Unlike one straight function call, explicit conditional edges route clarification, errors or one correction attempt.")
        st.markdown("**Groq-hosted LLM** receives an approved question and permitted schema and proposes SQL or clarification. It does not execute the query. The original provider adapter sends no returned result rows.")
        st.markdown("**MCP** defines named schema/query tools. The existing official client initializes the local JSON-RPC stdio server, discovers its tools and invokes them across a process boundary. MCP is a tool protocol, not the LLM or database.")
        st.markdown("**DuckDB** executes the validated query on local analytical tables. The original graph allows at most two generation attempts and three tool calls. A rejected/binding-failed query can receive one bounded correction; persistent errors stop safely. Explanations are grounded in returned rows.")
        st.markdown(f"[Agent graph]({REPOSITORY}/blob/main/src/citypulse_ai/sqlpilot/graph.py) · "
                    f"[MCP client]({REPOSITORY}/blob/main/src/citypulse_ai/sqlpilot/client.py) · "
                    f"[SQL safety core]({REPOSITORY}/blob/main/src/citypulse_ai/sqlpilot/core.py)")
    with st.expander("Read-only safety and sample provenance"):
        st.write("The visitor can choose only six query IDs, not edit SQL or file paths. The original DuckDB AST policy permits one SELECT on two physical allowlisted tables and approved columns/functions. Writes, multiple statements, external files/network access, table functions, extensions and hidden source columns are blocked.")
        st.write("Each execution uses a fresh child process, read-only DuckDB connection, one thread, 64 MB engine memory, no spill and a five-second deadline. Results are capped at 100 rows and 128 KiB. Engine memory is not total process RSS; this is defense in depth for our trusted small database, not a universal hostile-database sandbox.")
        schema_rows = [{"Table": table, "Column": column, "Type": dtype,
                        "Sample rows": definition["sample_rows"]}
                       for table, definition in manifest["schema"].items() for column, dtype in definition["columns"].items()]
        st.dataframe(pd.DataFrame(schema_rows), hide_index=True, width="stretch")
        st.caption("Only permitted timestamp/station/duration/count columns are packaged. Ride IDs, source paths/row IDs, helper fields and unrelated views were excluded. The exporter checked all six results against the original read-only database; runtime checks the packaged database hash and result agreement.")
        st.code("Packaged sample SHA-256: " + manifest["outputs"]["sample.duckdb"]["sha256"], language=None)
        st.caption("Sample UTC start range: " + " to ".join(manifest["source_period_utc"]))
    st.subheader("Original live LLM evaluation - separate evidence")
    evaluation = data["evaluation"]
    cards = st.columns(3)
    cards[0].metric("Correct original outcomes", f"{evaluation['correct']} / {evaluation['cases_evaluated']}")
    cards[1].metric("Correct answerable results", f"{evaluation['answerable_correct_results']} / {evaluation['answerable_cases']}")
    cards[2].metric("Original median latency", f"{evaluation['median_latency_seconds']:.3f}s")
    st.write("The saved genuine Groq GPT OSS 20B baseline had incorrect top-station results, two weekday query errors, and an ambiguous question answered instead of clarified. Exact causes cannot be established from that summary alone.")
    st.warning("The original live report did not preserve generated SQL or returned rows. The reference SQL and newly executed results above are curated offline examples, not reconstructed Groq outputs. Six correct outcomes out of nine is a small initial baseline, not general text-to-SQL accuracy or a security guarantee.")
    with st.expander("Original nine-case outcomes"):
        st.dataframe(pd.DataFrame([{"Case": r["id"], "Status": r["status"], "Correct": r["correct"],
                                   "Attempts": r["attempts"], "Latency (s)": r["latency_seconds"]}
                                  for r in evaluation["cases"]]), hide_index=True, width="stretch")
    st.markdown(f"[SQLPilot architecture and limitations]({DOCS}sqlpilot_release.md)")
